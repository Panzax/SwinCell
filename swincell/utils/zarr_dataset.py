"""
Dataset class for Zarr cube data compatible with SwinCell training.
"""

import os
from typing import Dict, List, Optional

import torch
from monai import data, transforms
from monai.transforms import MapTransform

from swincell.utils.data_utils import flow_reshaped
from swincell.utils.zarr_metadata_reader import (
    CubeROI,
    get_roi_list,
    load_training_metadata,
)
from swincell.utils.zarr_reader import load_zarr_cube


class LoadZarrImaged(MapTransform):
    """
    MONAI transform to load image and label from Zarr cube.

    This transform replaces LoadImaged for Zarr-backed data.
    Expects data dict with 'image' and 'label' keys containing zarr paths.
    """

    def __init__(self, keys, image_channel: int = 0, label_channel: int = 1, allow_missing_keys: bool = False):
        super().__init__(keys, allow_missing_keys)
        self.image_channel = image_channel
        self.label_channel = label_channel

    def __call__(self, data: Dict) -> Dict:
        d = dict(data)
        
        # Load image from zarr path
        if "image" in d:
            image_path = d["image"]
            if isinstance(image_path, str) and os.path.exists(image_path):
                image, _ = load_zarr_cube(
                    image_path,
                    t_index=0,
                    image_channel=self.image_channel,
                    label_channel=self.label_channel,
                )
                d["image"] = image
        
        # Load label from zarr path
        if "label" in d:
            label_path = d["label"]
            if isinstance(label_path, str) and os.path.exists(label_path):
                _, label = load_zarr_cube(
                    label_path,
                    t_index=0,
                    image_channel=self.image_channel,
                    label_channel=self.label_channel,
                )
                d["label"] = label

        return d


class ZarrCubeDataset(torch.utils.data.Dataset):
    """
    Dataset for loading Zarr cubes with metadata.

    This dataset loads 3D volumes from Zarr files based on metadata,
    and returns them in a format compatible with SwinCell transforms.
    """

    def __init__(
        self,
        roi_list: List[CubeROI],
        use_synthetic: bool = True,
        transform: Optional[transforms.Compose] = None,
    ):
        """
        Initialize ZarrCubeDataset.

        Args:
            roi_list: List of CubeROI objects
            use_synthetic: If True, use synthetic cube paths. If False, use real.
            transform: Optional MONAI transform pipeline
        """
        self.roi_list = roi_list
        self.use_synthetic = use_synthetic
        self.transform = transform

    def __len__(self) -> int:
        return len(self.roi_list)

    def __getitem__(self, idx: int) -> Dict:
        """
        Get a single sample.

        Returns:
            Dictionary with 'image' and 'label' keys containing zarr paths.
            The LoadZarrImaged transform will load the actual data.
        """
        roi = self.roi_list[idx]

        # Determine which cube path to use
        if self.use_synthetic:
            cube_path = roi.synthetic_cube_path
        else:
            cube_path = roi.real_cube_path

        if cube_path is None:
            raise ValueError(f"Cube path is None for ROI {roi.prepared_id}")
        
        if not os.path.exists(cube_path):
            raise FileNotFoundError(f"Zarr cube not found: {cube_path}")

        # Create data dictionary with paths (transforms will load the data)
        data_dict = {
            "image": cube_path,
            "label": cube_path,  # Same zarr file contains both image and label channels
        }

        # Apply transforms if provided
        if self.transform is not None:
            data_dict = self.transform(data_dict)

        return data_dict


def metadata_zarr_loader(args):
    """
    Create data loaders for Zarr cube dataset based on unified training metadata CSV.

    This function replaces folder_loader when using Zarr metadata.

    Args:
        args: Training arguments with metadata_root (must be path to training_metadata.csv),
              use_synthetic, etc.

    Returns:
        List containing [train_loader, val_loader]
    """
    print("Loading Zarr metadata-based dataset")

    # Get metadata CSV path
    metadata_csv = getattr(args, "metadata_root", None)
    if metadata_csv is None:
        raise ValueError(
            "metadata_root must be specified when using Zarr metadata. "
            "It should point to training_metadata.csv (generated by prepare_synthetic_metadata.py)"
        )

    import os
    if not os.path.isfile(metadata_csv) or not metadata_csv.endswith(".csv"):
        raise ValueError(
            f"metadata_root must be a CSV file path, got: {metadata_csv}. "
            "Please generate training_metadata.csv using prepare_synthetic_metadata.py"
        )

    use_synthetic = getattr(args, "use_synthetic", True)
    max_rois = getattr(args, "max_rois", None)

    print(f"Loading unified training metadata from {metadata_csv}")
    df = load_training_metadata(
        metadata_csv, filter_synthetic=use_synthetic, max_rois=max_rois
    )
    # Get ROI list (max_rois already applied in load_training_metadata)
    roi_list = get_roi_list(
        df, use_synthetic=use_synthetic, check_exists=True, max_rois=None
    )

    if len(roi_list) == 0:
        raise ValueError(
            f"No valid ROIs found for {'synthetic' if use_synthetic else 'real'} data"
        )

    if max_rois is not None:
        print(f"Found {len(roi_list)} ROIs (limited to {max_rois})")
    else:
        print(f"Found {len(roi_list)} ROIs")

    # Split into train/val
    if args.fold is None:
        # Simple 80/20 split
        split_index = int(len(roi_list) * 0.8)
        train_rois = roi_list[:split_index]
        val_rois = roi_list[split_index:]
    else:
        # K-fold split
        fold = args.fold
        val_start = (fold - 1) * len(roi_list) // 5
        val_end = fold * len(roi_list) // 5
        val_rois = roi_list[val_start:val_end]
        train_rois = [r for r in roi_list if r not in val_rois]

    print(f"Train ROIs: {len(train_rois)}, Val ROIs: {len(val_rois)}")

    # Determine image reshape size based on dataset
    if args.dataset == "colon":
        img_shape = (1300, 1030, 129)
        img_reshape = (
            img_shape[0] // args.downsample_factor,
            img_shape[1] // args.downsample_factor,
            img_shape[2] // args.downsample_factor,
        )
        img_reshape = tuple(int(e) for e in img_reshape)
    elif args.dataset == "allen":
        img_shape = (900, 600, 64)
        img_reshape = (
            img_shape[0] // args.downsample_factor,
            img_shape[1] // args.downsample_factor,
            img_shape[2] // args.downsample_factor,
        )
        img_reshape = tuple(int(e) for e in img_reshape)
    elif args.dataset == "nanolive":
        img_shape = (512, 512, 96)
        img_reshape = (
            img_shape[0] // args.downsample_factor,
            img_shape[1] // args.downsample_factor,
            img_shape[2] // args.downsample_factor,
        )
        img_reshape = tuple(int(e) for e in img_reshape)
    elif args.dataset == "zebrafish_memhistone" or args.dataset == "zebrafish":
        # Zebrafish mem-histone dataset: use cube_size from metadata
        # Typical cube_size is 128, but ROI dimensions vary
        # Use cube_size as the base dimension, or calculate from ROI if available
        if len(roi_list) > 0:
            # Calculate typical dimensions from first ROI
            roi = roi_list[0]
            z_size = roi.z_end - roi.z_start
            y_size = roi.y_end - roi.y_start
            x_size = roi.x_end - roi.x_start
            # Use cube_size as reference, but respect actual ROI dimensions
            img_shape = (max(y_size, roi.cube_size), max(x_size, roi.cube_size), max(z_size, roi.cube_size))
        else:
            # Default fallback: use cube_size 128 if no ROIs available
            img_shape = (128, 128, 128)
        
        img_reshape = (
            img_shape[0] // args.downsample_factor,
            img_shape[1] // args.downsample_factor,
            img_shape[2] // args.downsample_factor,
        )
        img_reshape = tuple(int(e) for e in img_reshape)
    else:
        # Default: use cube_size from metadata if available
        if len(roi_list) > 0:
            cube_size = roi_list[0].cube_size
            img_reshape = (cube_size, cube_size, cube_size)
        else:
            img_reshape = None
            print("Warning: dataset not defined and no ROIs found, img_reshape set to None")

    # Define transforms
    train_transform = transforms.Compose(
        [
            LoadZarrImaged(keys=["image", "label"]),
            transforms.EnsureChannelFirstd(keys=["image", "label"]),
            flow_reshaped(keys=["label"]),
            transforms.Resized(keys=["image", "label"], spatial_size=img_reshape)
            if img_reshape is not None
            else transforms.Identityd(keys=["image", "label"]),
            transforms.ScaleIntensityRanged(
                keys=["image"],
                a_min=args.a_min,
                a_max=args.a_max,
                b_min=args.b_min,
                b_max=args.b_max,
                clip=True,
            ),
            transforms.RandSpatialCropSamplesd(
                keys=["image", "label"],
                roi_size=[args.roi_x, args.roi_y, args.roi_z],
                num_samples=2,
                random_center=True,
                random_size=False,
            ),
            transforms.ToTensord(keys=["image", "label"]),
        ]
    )

    val_transform = transforms.Compose(
        [
            LoadZarrImaged(keys=["image", "label"]),
            transforms.EnsureChannelFirstd(keys=["image", "label"]),
            flow_reshaped(keys=["label"]),
            transforms.Resized(keys=["image", "label"], spatial_size=img_reshape)
            if img_reshape is not None
            else transforms.Identityd(keys=["image", "label"]),
            transforms.ScaleIntensityRanged(
                keys=["image"],
                a_min=args.a_min,
                a_max=args.a_max,
                b_min=args.b_min,
                b_max=args.b_max,
                clip=True,
            ),
            transforms.RandSpatialCropSamplesd(
                keys=["image", "label"],
                roi_size=[args.roi_x, args.roi_y, args.roi_z],
                num_samples=2,
                random_center=True,
                random_size=False,
            ),
            transforms.ToTensord(keys=["image", "label"]),
        ]
    )

    # Create datasets
    train_ds = ZarrCubeDataset(train_rois, use_synthetic=use_synthetic, transform=train_transform)
    val_ds = ZarrCubeDataset(val_rois, use_synthetic=use_synthetic, transform=val_transform)

    # Create samplers for distributed training
    from swincell.utils.data_utils import Sampler

    train_sampler = Sampler(train_ds) if args.distributed else None
    val_sampler = Sampler(val_ds, shuffle=False) if args.distributed else None

    # Create data loaders
    train_loader = data.DataLoader(
        train_ds,
        batch_size=args.batch_size,
        shuffle=(train_sampler is None),
        num_workers=args.workers,
        sampler=train_sampler,
        pin_memory=True,
    )

    val_loader = data.DataLoader(
        val_ds,
        batch_size=1,
        shuffle=False,
        num_workers=args.workers,
        sampler=val_sampler,
        pin_memory=True,
    )

    return [train_loader, val_loader]

